import { createHash } from 'node:crypto';
import { access, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build, version as esbuildVersion } from 'esbuild';
import { loadConfig, toPosix } from './config.mjs';
import { writeSnapshot } from './snapshot.mjs';
import { extractTokens } from './tokens.mjs';

const lab = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = 'opendesign-entry.ts';
const ASSET_EXTENSIONS = ['.svg', '.png', '.jpg', '.jpeg', '.gif', '.webp', '.woff', '.woff2'];
const SNAPSHOT_PLACEHOLDER = '__OPENDESIGN_SNAPSHOT_ID__';
const EXPORTER_FILES = [
  'exporter/export.mjs',
  'exporter/config.mjs',
  'exporter/snapshot.mjs',
  'exporter/tokens.mjs',
  'skills/compose-components/SKILL.md',
  'skills/sync-components/SKILL.md',
  'skills/sync-components/sync.mjs',
];

const read = async (file) => (await readFile(file, 'utf8')).replace(/\r\n?/g, '\n');
const hash = (data) => createHash('sha256').update(data).digest('hex');
const json = (data) => JSON.stringify(data, null, 2) + '\n';
const cell = (value = '') => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');

/**
 * Build a component package from a library configuration. The browser runtime
 * and the copied sources come from the same build, so they always match.
 */
export async function exportLibrary({ source, config: configFile, check = false }) {
  const config = await loadConfig({ source: path.resolve(source), config: configFile });
  const { root, out, components } = config;
  if ([config.source, root].some((dir) => isInside(dir, out))) {
    throw new Error(`Output ${out} must be a dedicated folder, not the source or its root`);
  }

  const compiled = await build({
    stdin: { contents: entry(config), resolveDir: root, sourcefile: ENTRY, loader: 'ts' },
    absWorkingDir: root,
    tsconfig: path.join(root, config.tsconfig),
    nodePaths: [path.join(root, 'node_modules')],
    bundle: true,
    write: false,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    charset: 'utf8',
    legalComments: 'eof',
    metafile: true,
    // Small assets referenced from components are inlined so the runtime stays offline.
    loader: Object.fromEntries(ASSET_EXTENSIONS.map((ext) => [ext, 'dataurl'])),
  });

  // Track every application input and the dependency files that reach the bundle.
  const contributing = new Set(
    Object.values(compiled.metafile.outputs).flatMap((output) =>
      Object.entries(output.inputs)
        .filter(([, input]) => input.bytesInOutput > 0)
        .map(([file]) => file),
    ),
  );
  const buildInputs = Object.keys(compiled.metafile.inputs).filter((file) => file !== ENTRY);
  const isDependency = (file) => toPosix(file).split('/').includes('node_modules');
  const localInputs = buildInputs.filter((file) => !isDependency(file));
  const sourceFiles = [...new Set([...localInputs, config.tokens, config.tsconfig])]
    .map((file) => toPosix(path.relative(root, path.resolve(root, file))))
    .sort();
  for (const file of sourceFiles) {
    if (file.startsWith('../') || path.isAbsolute(file)) {
      throw new Error(`Local dependency is outside the configured root: ${file}`);
    }
  }
  const inputFiles = [
    ...new Set([
      ...sourceFiles,
      ...buildInputs.filter((file) => isDependency(file) && contributing.has(file)),
      ...((await exists(path.join(root, 'package.json'))) ? ['package.json'] : []),
    ]),
  ];
  const inputs = (
    await Promise.all(
      inputFiles.map(async (file) => {
        const absolute = path.resolve(root, file);
        return {
          path: toPosix(path.relative(config.source, absolute)),
          sha256: hash(await read(absolute)),
        };
      }),
    )
  ).sort((a, b) => a.path.localeCompare(b.path));
  const configHash = hash(await read(config.file));
  const snapshot = hash(json({ inputs, config: configHash, esbuild: esbuildVersion })).slice(0, 12);

  const runtime = compiled.outputFiles[0].text;
  if (runtime.split(SNAPSHOT_PLACEHOLDER).length !== 2) {
    throw new Error('Expected exactly one snapshot marker in the runtime build');
  }
  const files = new Map();
  files.set('SKILL.md', await skill(config));
  // The sync skill travels with the package, so designers need only this repository.
  files.set('sync/SKILL.md', await syncSkill(config));
  files.set('sync/sync.mjs', await read(path.join(lab, 'skills/sync-components/sync.mjs')));
  files.set(
    'assets/ui.js',
    `/* ${config.title} components, snapshot ${snapshot}. Generated by OpenDesign Lab. Do not edit. */\n` +
      runtime.replace(SNAPSHOT_PLACEHOLDER, snapshot),
  );
  // Keep the source folder structure so relative imports and aliases remain discoverable.
  for (const file of sourceFiles) {
    files.set(`components/${file}`, await read(path.join(root, file)));
  }
  for (const { file } of components) {
    if (!files.has(`components/${file}`)) {
      throw new Error(`Component source is not part of the build: ${file}`);
    }
  }
  files.set('components/INDEX.md', index(config, snapshot, files));

  const stylesheet = await read(path.join(root, config.tokens));
  const tokens = extractTokens(stylesheet);
  if (!tokens.css) {
    throw new Error(`Expected at least one :root token block in ${config.tokens}`);
  }
  const tokensPath = toPosix(path.relative(config.source, path.join(root, config.tokens)));
  files.set(
    'assets/tokens.css',
    `/* ${config.title} token contract from ${tokensPath}, snapshot ${snapshot}. Do not edit. */\n${tokens.css}\n`,
  );
  files.set('references/DESIGN.md', design(config, snapshot, tokensPath, tokens.tokens));

  const exporter = {};
  for (const file of EXPORTER_FILES) {
    exporter[file] = hash(await read(path.join(lab, file)));
  }
  files.set(
    'source-lock.json',
    json({
      name: config.name,
      snapshot,
      textEncoding: 'utf8-lf',
      components: components.map(({ tag, file }) => ({
        tag,
        file: toPosix(path.relative(config.source, path.join(root, file))),
      })),
      dependencies: await dependencies(root, contributing),
      tools: { esbuild: esbuildVersion },
      exporter: { ...exporter, config: configHash },
      inputs,
      outputs: Object.fromEntries([...files].map(([file, content]) => [file, hash(content)])),
    }),
  );

  const { changed, removed } = await writeSnapshot(out, files, { check });
  return { config, snapshot, sourceFiles, tokens: tokens.tokens, changed, removed };
}

// The entry imports real component modules; no implementation is recreated.
function entry({ name, components, styles }) {
  const modules = [...new Set(components.map(({ file }) => file))];
  return [
    ...modules.map((file) => `import ${JSON.stringify('./' + file)};`),
    ...styles.map(
      ([exported, file], i) =>
        `import { ${exported} as style${i} } from ${JSON.stringify('./' + file)};`,
    ),
    ...(styles.length
      ? [
          `const style = document.createElement('style');`,
          `style.dataset.opendesignComponents = ${JSON.stringify(name)};`,
          `style.textContent = [${styles.map((_, i) => `style${i}`).join(', ')}]`,
          `  .map((value) => value.cssText ?? String(value)).join('\\n');`,
          'document.head.append(style);',
        ]
      : []),
    `globalThis.OPENDESIGN_COMPONENTS = Object.freeze(${JSON.stringify({
      name,
      snapshot: SNAPSHOT_PLACEHOLDER,
      tags: components.map(({ tag }) => tag),
    })});`,
  ].join('\n');
}

async function skill({ name, title, components }) {
  const template = await read(path.join(lab, 'skills/compose-components/SKILL.md'));
  const tags = components.map(({ tag }) => tag);
  const listed =
    tags.length > 8
      ? `${tags.slice(0, 8).join(', ')} and ${tags.length - 8} more`
      : tags.join(', ');
  const description =
    `Compose and iterate OpenDesign prototypes with the real ${title} components (${listed}). ` +
    'Use the bundled runtime and inspect matching original component sources on demand instead of recreating controls.';
  const result = template
    .replace(/^name: compose-components$/m, `name: ${name}-compose`)
    .replace(/^description: .*$/m, `description: ${JSON.stringify(description)}`);
  if (!result.includes(`name: ${name}-compose`)) {
    throw new Error('Composition template must contain "name: compose-components"');
  }
  return result;
}

async function syncSkill({ name, title }) {
  const template = await read(path.join(lab, 'skills/sync-components/SKILL.md'));
  const description =
    `Get the latest ${title} components. Pulls the designer's local checkout of the source repository ` +
    'and verifies the committed component snapshot. Use when the designer asks to sync or update components.';
  const result = template
    .replace(/^name: sync-components$/m, `name: ${name}-sync`)
    .replace(/^description: .*$/m, `description: ${JSON.stringify(description)}`)
    .replaceAll('--library <library>', `--library ${name}`);
  if (!result.includes(`name: ${name}-sync`) || !result.includes(`--library ${name}`)) {
    throw new Error('Sync template must contain "name: sync-components" and "--library <library>"');
  }
  return result;
}

function index({ title, components }, snapshot, files) {
  return [
    `# ${title} components`,
    '',
    `Snapshot \`${snapshot}\`. Read only the components you need.`,
    '',
    ...components.map(({ tag, file, purpose }) => {
      const lines = files.get(`components/${file}`).trimEnd().split('\n').length;
      return `- [${tag}](${file})${purpose ? ` - ${purpose}` : ''} (${lines} lines)`;
    }),
    '',
    'Small component: read its source. Large component: first locate public properties, types, slots and events; read implementation details only when needed.',
    'Follow local imports here. TypeScript aliases are recorded in [tsconfig.json](tsconfig.json). Third-party packages are bundled for the browser and are not copied as source.',
    '[Design foundations](../references/DESIGN.md) gives a short token overview. Layouts remain open-ended.',
    '',
  ].join('\n');
}

function design({ title, tokenSummary }, snapshot, tokensPath, tokens) {
  const overview = tokenSummary.length
    ? [
        '| Source token | Value |',
        '| --- | --- |',
        ...tokenSummary.map((name) => `| ${name} | ${cell(tokens.get(name))} |`),
      ]
    : Object.entries(
        Object.groupBy([...tokens.keys()], (name) => name.split('-').slice(0, 3).join('-')),
      ).map(([group, names]) => `- \`${group}\`: ${names.map((n) => `\`${n}\``).join(', ')}`);
  return [
    `# ${title} UI foundations`,
    '',
    `Generated from \`${tokensPath}\`, snapshot \`${snapshot}\`.`,
    '',
    'Use the original runtime and its source tokens. Component appearance is supplied by the library; author only surrounding layout CSS. Font files are not bundled; font stacks fall back to the fonts available on the viewing machine.',
    '',
    ...overview,
    '',
    `tokens.css contains every \`:root\` rule from the source stylesheet (${tokens.size} tokens), including theme variants, so free compositions can use any source token. Keep it together with the matching component build. Layout wrappers and slotted content may be freely composed; rendered component internals are owned by the components.`,
    '',
  ].join('\n');
}

async function dependencies(root, contributing) {
  const found = {};
  for (const file of contributing) {
    const parts = toPosix(file).split('/');
    const at = parts.lastIndexOf('node_modules');
    if (at === -1) {
      continue;
    }
    const length = parts[at + 1]?.startsWith('@') ? 2 : 1;
    const name = parts.slice(at + 1, at + 1 + length).join('/');
    if (!(name in found)) {
      const manifest = path.join(root, ...parts.slice(0, at + 1 + length), 'package.json');
      found[name] = JSON.parse(await read(manifest)).version;
    }
  }
  return Object.fromEntries(Object.entries(found).sort(([a], [b]) => a.localeCompare(b)));
}

function isInside(target, candidate) {
  const relative = path.relative(candidate, target);
  return !relative || (!relative.startsWith('..') && !path.isAbsolute(relative));
}

function exists(file) {
  return access(file).then(
    () => true,
    () => false,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const arg = (name) => {
    const at = process.argv.indexOf(name);
    return at === -1 ? undefined : process.argv[at + 1];
  };
  const source = arg('--source');
  if (!source) {
    console.error(
      'Usage: node exporter/export.mjs --source <repository> [--config <file>] [--check]',
    );
    process.exit(2);
  }
  const check = process.argv.includes('--check');
  const result = await exportLibrary({ source, config: arg('--config'), check });
  const { config, changed, removed } = result;
  const target = toPosix(path.relative(process.cwd(), config.out)) || '.';
  if (check && (changed.length || removed.length)) {
    console.error(
      `Snapshot drift in ${target}; run the export without --check for an intentional refresh:\n${[
        ...changed,
        ...removed.map((file) => `remove ${file}`),
      ].join('\n')}`,
    );
    process.exitCode = 1;
  } else {
    console.log(
      `${check ? 'Verified' : 'Exported'} ${config.title} snapshot ${result.snapshot} to ${target}: ` +
        `${config.components.length} components, ${result.sourceFiles.length} source files, ` +
        `${result.tokens.size} tokens; ${changed.length} changed, ${removed.length} removed.`,
    );
  }
}
