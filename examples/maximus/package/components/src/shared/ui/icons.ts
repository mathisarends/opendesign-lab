export type IconName = keyof typeof icons;

// Lucide ships icons as data, not markup; serialised once so every render reuses the string.
const markup = Object.fromEntries(
  Object.entries(icons).map(([name, node]) => [
    name,
    node
      .map(([tag, attrs]) => {
        const attributes = Object.entries(attrs).map(([key, value]) => `${key}="${value}"`);
        return `<${tag} ${attributes.join(" ")}/>`;
      })
      .join(""),
  ]),
) as Record<IconName, string>;

export function icon(name: IconName, size = 20): TemplateResult<2> {
  return svg`<svg width=${size} height=${size} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${unsafeSVG(markup[name])}</svg>`;
}
